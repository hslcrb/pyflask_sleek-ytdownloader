#!/usr/bin/env python3
"""Assemble a Windows x64 asset from pinned CPython and wheels on any host."""

import argparse
from pathlib import Path
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
PACKAGING = ROOT / "packaging/windows"
RUNTIME = "python-3.13.17-embed-amd64.zip"
RUNTIME_HASH = "9e35319bffedab8b36ad44d8f377cb4f1733bcec257a0b6d04d94f01486ddb38"
APP_FILES = ("app.py", "metadata.py", "windows_folder.py", "info.json", "LICENSE", "LICENSE_ko.md")


def digest(path):
    with path.open("rb") as file:
        from hashlib import file_digest
        return file_digest(file, "sha256").hexdigest()


def stage(root, inputs):
    runtime = inputs / RUNTIME
    if digest(runtime) != RUNTIME_HASH:
        raise ValueError(f"SHA-256 mismatch: {RUNTIME}")
    runtime_dir = root / "runtime"
    vendor = root / "vendor"
    app = root / "app"
    with ZipFile(runtime) as vendor_zip:
        vendor_zip.extractall(runtime_dir)

    # The embedded interpreter reads only these explicit local paths.
    (runtime_dir / "python313._pth").write_bytes(b"python313.zip\r\n.\r\n..\\vendor\r\n..\\app\r\n")
    subprocess.run([
        sys.executable, "-m", "pip", "install",
        "--disable-pip-version-check", "--no-deps", "--no-compile",
        "--no-index", "--only-binary=:all:", "--require-hashes",
        "--platform", "win_amd64", "--implementation", "cp",
        "--python-version", "3.13", "--abi", "cp313",
        "--find-links", str(inputs / "wheels"), "--target", str(vendor),
        "-r", str(PACKAGING / "requirements-win-amd64.lock"),
    ], check=True)

    # Console entry points generated by pip are host-dependent and unused.
    if (vendor / "bin").is_dir():
        shutil.rmtree(vendor / "bin")
    if (vendor / "Scripts").is_dir():
        shutil.rmtree(vendor / "Scripts")
    # Wheel metadata with host-dependent absolute paths is not needed at runtime.
    for dist in vendor.glob("*.dist-info"):
        for name in ("RECORD", "REQUESTED"):
            (dist / name).unlink(missing_ok=True)

    app.mkdir()
    for name in APP_FILES:
        shutil.copyfile(ROOT / name, app / name)
    shutil.copyfile(PACKAGING / "launch.py", app / "launch.py")
    shutil.copytree(ROOT / "static", app / "static")
    shutil.copytree(ROOT / "templates", app / "templates")
    shutil.copyfile(PACKAGING / "README.txt", root / "README.txt")
    script = (PACKAGING / "SleekDownloader.cmd").read_bytes().replace(b"\r\n", b"\n")
    (root / "SleekDownloader.cmd").write_bytes(script.replace(b"\n", b"\r\n"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path, help="Official embeddable ZIP and wheels/ directory")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if args.output.exists():
        parser.error("output already exists")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory() as tmp:
        root = Path(tmp) / "SleekDownloader"
        stage(root, args.inputs.resolve())
        with ZipFile(args.output, "x", compression=ZIP_DEFLATED, compresslevel=9) as zip_file:
            for file in sorted(p for p in root.rglob("*") if p.is_file()):
                info = ZipInfo(file.relative_to(root.parent).as_posix())
                info.compress_type = ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                zip_file.writestr(info, file.read_bytes(), compresslevel=9)
    print(f"{digest(args.output)}  {args.output.name}")


if __name__ == "__main__":
    main()
